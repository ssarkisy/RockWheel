#!/usr/bin/env python3
# The reference for tests/wheel: the click wheel's code as it was at BASE,
# taken out of git verbatim. Run from anywhere in the repository:
#
#   python3 -I tests/wheel/make_ref.py          writes tests/wheel/ref/
#   python3 -I tests/wheel/make_ref.py --check  compares ref/ with BASE
#
# ref/button-clickwheel.c is the whole driver; ref/apps.c holds the lines of
# button.c, list.c and wps.c that turned a wheel event into rows and steps,
# each block between "BASE <file>:<first>-<last>" and "END" markers, around
# them only the wrappers that call them (ref_prelude.h stubs what they call).

import os, subprocess, sys

BASE = '1be9ae95b6'
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = subprocess.check_output(['git', '-C', HERE, 'rev-parse', '--show-toplevel'],
                               text=True).strip()

def show(path):
    return subprocess.check_output(['git', '-C', ROOT, 'show', f'{BASE}:{path}'],
                                   text=True)

def lines(path, first, last):
    text = show(path).split('\n')
    block = '\n'.join(text[first - 1:last]) + '\n'
    return f'/* BASE {path}:{first}-{last} */\n' + block + '/* END */\n'

def apps():
    out = [
        '/* The reference: generated by make_ref.py from ' + BASE + ', do not edit */\n',
        '#include "ref_prelude.h"\n\n',
        lines('firmware/drivers/button.c', 659, 737), '\n',
        lines('apps/gui/list.c', 783, 784), '\n',
        lines('apps/gui/list.c', 916, 922), '\n',
        'void ref_list_rows(unsigned int data, int nb_items, int lines,\n'
        '                   struct ref_rows *out)\n{\n'
        '    struct gui_synclist list = { .nb_items = nb_items };\n'
        '    struct gui_synclist *lists = &list;\n'
        '    bool quick_step = false;\n'
        '    ref_action_data = data;\n'
        '    ref_nb_lines = lines;\n'
        '    ref_nb_lines_calls = 0;\n\n',
        lines('apps/gui/list.c', 995, 1025),
        '#endif\n'
        '    out->rows = next_item_modifier;\n'
        '    out->steps = wheel_steps;\n'
        '    out->quick = quick_step;\n'
        '    out->nb_lines_calls = ref_nb_lines_calls;\n'
        '}\n\n'
        '/* the keyclick callback\'s quick step, of the data as it came */\n'
        'bool ref_list_quick_click(unsigned int data, int nb_items)\n{\n'
        '    struct gui_synclist list = { .nb_items = nb_items };\n'
        '    return quick_scroll_step(&list, data);\n}\n\n',
        lines('apps/gui/wps.c', 858, 866), '\n',
        'int ref_wps_steps(unsigned int data)\n{\n'
        '    ref_action_data = data;\n'
        '    return wheel_steps();\n}\n\n'
        'int ref_wps_lyrics_ticks(unsigned int data)\n{\n'
        '    ref_action_data = data;\n',
        lines('apps/gui/wps.c', 922, 925),
        '    return ticks;\n}\n\n'
        'int ref_wps_volume_steps(unsigned int data)\n{\n'
        '    ref_action_data = data;\n',
        lines('apps/gui/wps.c', 1440, 1444),
        '    return steps;\n}\n',
    ]
    return ''.join(out)

def files():
    return {
        'button-clickwheel.c': show('firmware/target/arm/ipod/button-clickwheel.c'),
        'apps.c': apps(),
    }

def main():
    ref = os.path.join(HERE, 'ref')
    bad = 0
    for name, text in files().items():
        path = os.path.join(ref, name)
        if '--check' in sys.argv:
            with open(path) as f:
                same = f.read() == text
            print(('same   ' if same else 'DIFFERS') + ' ' + path)
            bad += not same
        else:
            with open(path, 'w') as f:
                f.write(text)
            print('wrote ' + path)
    return 1 if bad else 0

sys.exit(main())
