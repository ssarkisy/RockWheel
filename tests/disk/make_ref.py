#!/usr/bin/env python3
# The reference for tests/disk: the "disk free, don't wake it" predicates as
# they were at BASE, taken out of git verbatim; and the new ones, taken out of
# the tree as it is. Run from anywhere in the repository:
#
#   python3 -I tests/disk/make_ref.py          writes tests/disk/ref/disk_ref.c
#   python3 -I tests/disk/make_ref.py --check  compares it with BASE
#   python3 -I tests/disk/make_ref.py --new <file>
#                                             apps/misc.c's disk_is_flash() and
#                                             disk_free_for_ui(), into file
#   python3 -I tests/disk/make_ref.py --targets
#                                             fails if a target has a hard disk
#                                             (HAVE_DISK_STORAGE) that isn't ATA
#
# Each block of the reference is between "BASE <file>:<first>-<last>" and
# "END" markers. menu_cover.c's are there too: it keeps its own copy until
# the cover work moves it onto the shared one, and the test shows how.

import os, re, subprocess, sys

BASE = '1be9ae95b6'
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = subprocess.check_output(['git', '-C', HERE, 'rev-parse', '--show-toplevel'],
                               text=True).strip()

def show(path):
    return subprocess.check_output(['git', '-C', ROOT, 'show', f'{BASE}:{path}'],
                                   text=True)

def lines(path, first, last):
    text = show(path).split('\n')
    block = '\n'.join(text[first - 1:last]) + '\n'
    return f'/* BASE {path}:{first}-{last} */\n' + block + '/* END */\n'

def ref():
    return ''.join([
        '/* The reference: generated by make_ref.py from ' + BASE + ', do not edit */\n\n',
        '#define photos_panel_disk_free ref_photos_panel_disk_free\n',
        lines('apps/photos_panel.c', 282, 297), '\n',
        lines('apps/tagtree.c', 3087, 3097), '\n',
        lines('apps/gui/skin_engine/menu_cover.c', 1085, 1090),
        lines('apps/gui/skin_engine/menu_cover.c', 1094, 1094),
        lines('apps/gui/skin_engine/menu_cover.c', 1104, 1127), '\n',
        'bool ref_songs_orders_disk_on(void) { return songs_orders_disk_on(); }\n',
        'bool ref_menu_cover_disk_spins(void) { return disk_spins(); }\n',
        'bool ref_menu_cover_disk_free(void) { return disk_free(); }\n',
    ])

def function(text, head):
    """the definition that starts with the line head, to its closing brace"""
    src = text.split('\n')
    starts = [i for i, l in enumerate(src) if l == head]
    if len(starts) != 1:
        sys.exit(f'make_ref.py: {len(starts)} definitions "{head}"')
    end = next(i for i in range(starts[0], len(src)) if src[i] == '}')
    return '\n'.join(src[starts[0]:end + 1]) + '\n'

def new(out):
    with open(os.path.join(ROOT, 'apps/misc.c')) as f:
        text = f.read()
    with open(out, 'w') as f:
        f.write('/* apps/misc.c\'s, taken out by make_ref.py --new */\n\n'
                + function(text, 'bool disk_is_flash(void)') + '\n'
                + function(text, 'bool disk_free_for_ui(long margin)'))

def targets():
    """tagtree.c's copy asked such a disk to spin, the shared one doesn't"""
    folder = os.path.join(ROOT, 'firmware/export/config')
    disks = bad = 0
    for name in sorted(os.listdir(folder)):
        with open(os.path.join(folder, name), errors='replace') as f:
            text = f.read()
        if not re.search(r'^\s*#\s*define\s+HAVE_DISK_STORAGE\b', text, re.M):
            continue
        disks += 1
        storage = re.findall(r'^\s*#\s*define\s+CONFIG_STORAGE\b(.*)$', text, re.M)
        if not storage or any('STORAGE_ATA' not in s for s in storage):
            print('a hard disk that isn\'t ATA: ' + name)
            bad += 1
    print(f'targets with a hard disk: {disks}, all ATA' if not bad else '')
    return 1 if bad else 0

def main():
    if '--targets' in sys.argv:
        return targets()
    if '--new' in sys.argv:
        new(sys.argv[sys.argv.index('--new') + 1])
        return 0
    path = os.path.join(HERE, 'ref', 'disk_ref.c')
    text = ref()
    if '--check' in sys.argv:
        with open(path) as f:
            same = f.read() == text
        print(('same   ' if same else 'DIFFERS') + ' ' + path)
        return 0 if same else 1
    with open(path, 'w') as f:
        f.write(text)
    print('wrote ' + path)
    return 0

sys.exit(main())
