/* The following header is generated by the build system and only defines
   MAX_LANGUAGE_SIZE to be the size of the largest currently available
   language! */
#include "max_language_size.h"

/* These defines must match the initial bytes in the binary lang file */
/* See tools/genlang (TODO: Use common include for both) */
#define LANGUAGE_COOKIE   0x1a
/* RockWheel's own count from 0x86 (upstream's is 0x06): raised whenever the
   phrases' numbers move, by a phrase put before the last one of english.lang
   or by a feature the target gains or loses (0x87: the iPod Video's alarm).
   A .lng of another count is refused, English shows, and the release's own
   .lng files take its place */
#define LANGUAGE_VERSION  0x87

#define LANGUAGE_FLAG_RTL         0x01
#define LANGUAGE_FLAG_UNITS_FIRST 0x02

#define HEADER_SIZE 4
#define SUBHEADER_SIZE 6

static unsigned char language_buffer[MAX_LANGUAGE_SIZE];
static unsigned char lang_options = 0;

void lang_init(const unsigned char *builtin, unsigned char **dest, int count)
{
    while(count--) {
        *dest++ = (unsigned char *)builtin;
        /* advance pointer to next string */
        builtin += strlen((char *)builtin) + 1;
    }
}

int lang_load(const char *filename, const unsigned char *builtin,
              unsigned char **dest, unsigned char *buffer,
              unsigned int user_num, int max_lang_size,
              unsigned int max_id)
{
    int lang_size;
    int fd = open(filename, O_RDONLY);
    int retcode=0;
    unsigned char lang_header[HEADER_SIZE];
    unsigned char sub_header[SUBHEADER_SIZE];
    unsigned int id, foffset;

    if(fd < 0)
        return 1;

    if(read(fd, lang_header, HEADER_SIZE) == HEADER_SIZE &&
       ((lang_header[0] == LANGUAGE_COOKIE) &&
       (lang_header[1] == LANGUAGE_VERSION) &&
       (lang_header[2] == TARGET_ID))) {
        /* jump to the proper entry in the table of subheaders */
        lseek(fd, user_num * SUBHEADER_SIZE, SEEK_CUR);
        if (read(fd, sub_header, SUBHEADER_SIZE) != SUBHEADER_SIZE)
        {
            DEBUGF("Language %s bad subheader %u\n", filename, user_num);
            retcode = 4;
        }
        /* read in information about the requested lang */
#if 0   /* unused */
        unsigned int num_strings = (sub_header[0]<<8) | sub_header[1];
#endif
        lang_size = (sub_header[2]<<8) | sub_header[3];
        foffset = (sub_header[4]<<8) | sub_header[5];
        if(lang_size <= max_lang_size) {
            /* initialize with builtin */
            lang_init(builtin, dest, max_id);
            lseek(fd, foffset, SEEK_SET);
            read(fd, buffer, lang_size);
            buffer[max_lang_size - 1] = '\0'; /* ensure buffer is null terminated */
            while(lang_size>3) {
                id = ((buffer[0]<<8) | buffer[1]); /* get two-byte id */
                buffer += 2;                       /* pass the id */
                if(id < max_id) {
#if 0
                    DEBUGF("%2x New: %30s ", id, buffer);
                    DEBUGF("Replaces: %s\n", dest[id]);
#endif
                    dest[id] = buffer; /* point to this string */
                }
                while(*buffer) {               /* pass the string */
                    lang_size--;
                    buffer++;
                }
                lang_size-=3; /* the id and the terminating zero */
                buffer++;     /* pass the terminating zero-byte */
            }
        }
        else {
            DEBUGF("Language %s too large: %d\n", filename, lang_size);
            retcode = 2;
        }
    }
    else {
        DEBUGF("Illegal language file\n");
        retcode = 3;
    }
    close(fd);
    lang_options = retcode ? 0 : lang_header[3];
    return retcode;
}

/* The phrases of the plugins of Extras, the games, the clock, the calendar and
   the stopwatch: none in the core, in English or another language, as most
   never open them. A plugin of Extras loads them as it starts, from the
   language files' second section, into its own memory, and they're gone
   again when it quits; until then they're empty. */
static const unsigned char no_phrase[] = "";

void lang_extras_reset(void)
{
    /* from LANG_LAST_INDEX_IN_ARRAY, which no phrase is, to theirs */
    for (int i = LANG_LAST_INDEX_IN_ARRAY; i < LANG_LAST_EXTRAS_INDEX; i++)
        language_strings[i] = (unsigned char *)no_phrase;
}

/* a language file's section of extras into buf, at most size: its phrases
   in their places among language_strings; how much of buf it took, or -1 */
static int lang_extras_read(const char *filename, unsigned char *buf, size_t size)
{
    unsigned char head[HEADER_SIZE + 2 * SUBHEADER_SIZE];
    int fd = open(filename, O_RDONLY);
    int took = -1;
    if (fd < 0)
        return -1;
    if (read(fd, head, sizeof(head)) == (ssize_t)sizeof(head)
        && head[0] == LANGUAGE_COOKIE && head[1] == LANGUAGE_VERSION
        && head[2] == TARGET_ID)
    {
        /* two sections, the core's right after their subheaders and the
           extras' right after it: a file of one section, from an older
           build, has its first phrase where the second subheader would be */
        const unsigned char *core = head + HEADER_SIZE;
        const unsigned char *sub = core + SUBHEADER_SIZE;
        const size_t core_len = (core[2] << 8) | core[3];
        const off_t core_at = (core[4] << 8) | core[5];
        const size_t len = (sub[2] << 8) | sub[3];
        const off_t at = (sub[4] << 8) | sub[5];
        if (core_at == HEADER_SIZE + 2 * SUBHEADER_SIZE
            && at == core_at + (off_t)core_len
            && len <= size && lseek(fd, at, SEEK_SET) == at
            && read(fd, buf, len) == (ssize_t)len)
        {
            const unsigned char *end = buf + len;
            unsigned char *p = buf;
            took = len;
            /* each a number of two bytes, then the phrase and its 0 */
            while (p + 3 <= end)
            {
                const unsigned int id = (p[0] << 8) | p[1];
                unsigned char *phrase = p + 2;
                p = phrase;
                while (p < end && *p)
                    p++;
                if (p >= end)
                    break; /* a file cut short */
                p++;
                if (id < LANG_LAST_EXTRAS_INDEX - LANG_LAST_INDEX_IN_ARRAY - 1)
                    language_strings[LANG_LAST_INDEX_IN_ARRAY + 1 + id] = phrase;
            }
        }
    }
    close(fd);
    return took;
}

int lang_extras_load(unsigned char *buf, size_t size)
{
    lang_extras_reset();
    /* English for all, as the core has it built in for its own; the
       language's over it, as a translation can lack some */
    const int took = lang_extras_read(LANG_DIR "/english.lng", buf, size);
    if (took < 0)
        return -1;
    const char *lang = (const char *)global_settings.lang_file;
    if (lang[0] && strcmp(lang, "english"))
    {
        char path[MAX_PATH];
        snprintf(path, sizeof(path), LANG_DIR "/%s.lng", lang);
        lang_extras_read(path, buf + took, size - took);
    }
    return 0;
}

int lang_core_load(const char *filename)
{
    const int rc = lang_load(filename, core_language_builtin, language_strings,
                             language_buffer, 0, MAX_LANGUAGE_SIZE,
                             LANG_LAST_INDEX_IN_ARRAY);
    if (rc == 0)
    {
        /* the ideographs in the forms of the language */
        const char *name = strrchr(filename, '/');
        name = name ? name + 1 : filename;
        font_set_han_form(!strcmp(name, "japanese.lng") ? FONT_HAN_JP
                          : !strcmp(name, "chinese-trad.lng") ? FONT_HAN_TC
                          : FONT_HAN_SC);
        lyrics_forget(); /* wrapped again, as their rows keep the form */
    }
    return rc;
}

int lang_english_to_id(const char *english)
{
    int i;
    unsigned char *ptr = (unsigned char *) core_language_builtin;
    size_t ptrlen, len = strlen(english);
    for (i = 0; i < LANG_LAST_INDEX_IN_ARRAY; i++) {
        ptrlen = strlen((char *)ptr);
        if ((ptrlen == len) && memcmp(ptr, english, ptrlen) == 0)
            return i;
        ptr += ptrlen + 1; /* advance pointer to next string */
    }
    return -1;
}

const char * lang_id_to_english(int lang_id)
{
    int i;
    unsigned char *ptr = (unsigned char *) core_language_builtin;

    if (lang_id >= 0 && lang_id < LANG_LAST_INDEX_IN_ARRAY)
    {
        if (language_strings[0] == ptr) /* already in english */
            return str(lang_id);

        for (i = 0; i < LANG_LAST_INDEX_IN_ARRAY; i++) {
            if (i == lang_id)
                return ptr;
            ptr += strlen((char *)ptr) + 1; /* advance pointer to next string */
        }
    }
    return ""; /* Not found */
}

int lang_is_rtl(void)
{
    return (lang_options & LANGUAGE_FLAG_RTL) != 0;
}

int lang_units_first(void)
{
    return (lang_options & LANGUAGE_FLAG_UNITS_FIRST) != 0;
}
